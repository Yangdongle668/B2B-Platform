CREATE TABLE sys_audit_log (
  id            BIGINT        NOT NULL COMMENT '主键（TSID，时间有序）',
  site_id       BIGINT        NULL COMMENT '站点；系统级操作（登录、站点与模块管理、数据主体请求等）为空',
